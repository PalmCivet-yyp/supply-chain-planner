#!/usr/bin/env python3
"""Replay recorded public benchmark decisions without invoking an optimizer."""
import argparse
import gzip
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CHECKER_SHA256 = '86217df70345cf010fe60920da8f6826c3046a62773bdaac3beba1c03eea1dac'


def equivalent(actual, expected):
    if type(actual) is float and type(expected) in (int, float):
        return math.isclose(actual, expected, rel_tol=1e-10, abs_tol=1e-7)
    return actual == expected


def replay(data_dir):
    if not __debug__:
        raise ValueError('Run without -O: the frozen independent checker uses assertions.')
    checker = ROOT / 'scripts/scm/benchmark_checks.py'
    if hashlib.sha256(checker.read_bytes()).hexdigest() != CHECKER_SHA256:
        raise ValueError('The independent checker differs from the recorded experiment.')
    from scm.benchmark_checks import grade, compare
    manifest = json.loads((ROOT / 'assets/evaluation/public-optimization.json').read_text(encoding='utf-8'))
    if json.loads((data_dir / 'manifest.json').read_text(encoding='utf-8')) != manifest:
        raise ValueError('Dataset manifest differs from the recorded experiment.')
    cases = {c['id']: c for c in manifest['cases']}
    folder = ROOT / 'assets/evaluation/benchmark-31'
    decisions = json.loads(gzip.decompress((folder / 'recorded-decisions.json.gz').read_bytes()))
    totals = {}
    for mode in ('primary', 'repeat'):
        rows = json.loads((folder / (mode + '-results.json')).read_text(encoding='utf-8'))
        counts = dict(pairs=len(rows), v30_feasible=0, v31_feasible=0,
                      v30_target=0, v31_target=0, better=0, tie=0, worse=0, both_failed=0)
        for row in rows:
            case = cases[row['id']]
            path = data_dir / case['input']
            if hashlib.sha256(path.read_bytes()).hexdigest() != case['input_sha256']:
                raise ValueError('Input fingerprint differs: ' + case['id'])
            data = json.loads(path.read_text(encoding='utf-8'))
            key = row['id'] + '_' + str(row['seed'])
            grades = {}
            for version in ('v30', 'v31'):
                grades[version] = grade(data, decisions[mode][key][version], case['reference'])
                for field, value in grades[version].items():
                    if not equivalent(value, row['arms'][version].get(field)):
                        raise ValueError('Recorded grade differs: ' + '/'.join((mode, key, version, field)))
                counts[version + '_feasible'] += int(grades[version]['feasible'])
                counts[version + '_target'] += int(grades[version]['target_met'])
            change = compare(grades['v30'], grades['v31'], row['kind'])
            if change != row['change']:
                raise ValueError('Recorded paired outcome differs: ' + key)
            counts[change] += 1
        totals[mode] = counts
    return {'reproduced': True, 'search_invocations': 0, 'totals': totals,
            'scope': '100 primary instances plus 12 extra-seed pairs; repeat runs do not add unique instances.'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data', type=Path, required=True, help='Dataset generated by benchmark_supply_chain.py fetch')
    parser.add_argument('--out', type=Path, help='Optional new JSON result file')
    args = parser.parse_args()
    if args.out and args.out.exists():
        parser.error('Choose a new output file.')
    output = json.dumps(replay(args.data.resolve()), ensure_ascii=False, indent=2)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(output + '\n', encoding='utf-8')
    print(output)


if __name__ == '__main__':
    main()
